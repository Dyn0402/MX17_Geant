def curve(name, key='fit_depth_mm'):
    r = S[name]['rows']
    return np.array([x['p_mbar'] for x in r]), np.array([x[key] for x in r])


def p_needed(name, depth):
    p, d = curve(name)
    if depth > d.max():
        return float('inf')
    if depth < d.min():
        return 0.0
    return float(np.interp(depth, d, p))


def fmt_p(x):
    return '>10' if not np.isfinite(x) else ('0 (weight alone)' if x == 0 else f'{x:.1f}')


def at(name, pm, key='fit_depth_mm'):
    p, d = curve(name, key)
    return float(np.interp(pm, p, d))


