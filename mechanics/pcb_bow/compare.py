POS = (np.linspace(30, 370, 10)[:-1] + np.linspace(30, 370, 10)[1:]) / 2 - 200.0


def shape_of(n, ax):
    if n == 'parabola':
        return POS / 150.0, None
    rows = S[n]['rows']
    # the shape at the pressure whose depth is nearest the measured 1.7 mm (non-pressure scenarios: their p = 0 row)
    i = int(np.argmin([abs(r['fit_depth_mm'] - 1.7) for r in rows])) if n[0] != 'F' else 0
    return np.array(rows[i]['slope'][ax]), rows[i]['fit_depth_mm']


prof = {d: json.load(open(f'{FB}/profiles_{d}.json')) for d in DETS}
shape_res = {}
md += ['', '## 5. Shape test: measured w0 profiles vs the model slope shapes', '',
       'Each view: weighted fit w0 = c + α·s(u) (c = rigid tilt). χ² for 9 bins, 7 dof. det7 X has a faulty half '
       '(x < 200 mm), shown but excluded from the total. Depth implied by the tilt route assumes a flat cathode '
       '(r_f = ½) and v = the view\'s median ladder slope.', '',
       '| shape | ' + ' | '.join(f'{d} {p.upper()}' for d in DETS for p in 'xy') + ' | Σχ² (9 views) | implied depth (median) |',
       '|' + '---|' * 13]
for n, lab in SHAPES:
    if n != 'parabola' and n not in S: continue
    chis, depths = [], []
    for d in DETS:
        for ax in 'xy':
            P = prof[d][ax]
            y, e = np.array(P['w0']), np.array(P['w0_err'])
            s, D = shape_of(n, ax)
            ok = np.isfinite(y) & np.isfinite(e)
            Wt = 1 / e[ok] ** 2
            X = np.c_[np.ones(ok.sum()), s[ok]]
            beta = np.linalg.solve(X.T @ (X * Wt[:, None]), X.T @ (Wt * y[ok]))
            chi = float(np.sum(Wt * (y[ok] - X @ beta) ** 2))
            chis.append(chi)
            # implied depth: slope = alpha / (v r_f) * s; s is the model slope (mm/mm) for model depth D
            v = P['b_med']
            if n == 'parabola':
                # s = u/150 mm means slope = alpha/(v r_f) * u/150; a parabola h = k u^2/2 has slope k u -> depth k 150^2/2
                k = beta[1] / (v * 0.5) / 150.0
                depths.append(0.5 * k * 150.0 ** 2)
            else:
                depths.append(beta[1] / (v * 0.5) * D / 1.0)
            shape_res.setdefault(n, {})[f'{d}_{ax}'] = dict(chi2=chi, alpha=float(beta[1]), c=float(beta[0]))
    keep = [i for i in range(10) if i != 8]           # drop det7 X
    tot = sum(chis[i] for i in keep)
    shape_res[n]['total_chi2'] = tot
    shape_res[n]['implied_depth_median'] = float(np.median([depths[i] for i in keep]))
    md.append(f'| {lab} | ' + ' | '.join(f'{c:.0f}' for c in chis) + f' | {tot:.0f} | '
              f'{np.median([depths[i] for i in keep]):.2f} mm |')
out['shape_test'] = shape_res

